export const DICTIONARIES: Record<Locale, Dictionary> = { en, de, ar };

/** Replace {name} placeholders. */
export function fill(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}

/** "11.1" → "Grade 11 · 1st half-year" (localized). Unknown formats are shown as-is. */
export function formatSemester(semester: string, dict: Dictionary) {
  const match = /^(\d+)\.([12])$/.exec(semester);
  if (!match) return semester;
  const [, grade, half] = match;
  return fill(dict.library.semester, {
    grade,
    half: half === "1" ? dict.library.half1 : dict.library.half2,
  });
}

export function formatPageCount(n: number, dict: Dictionary) {
  if (n === 0) return dict.library.noPages;
  if (n === 1) return dict.library.onePage;
  if (n === 2) return dict.library.twoPages;
  // Arabic uses the plural for 3–10 and the singular form from 11 on.
  return fill(n <= 10 ? dict.library.pages : dict.library.manyPages, { n });
}

export function formatGradeCount(n: number, dict: Dictionary) {
  return n === 1 ? dict.grades.oneGrade : fill(dict.grades.gradesCount, { n });
}
